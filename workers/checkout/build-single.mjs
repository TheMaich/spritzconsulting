// Builds worker.single.js: worker.js and business-days.js in one file, to paste into the Cloudflare dashboard.
// Run: node build-single.mjs   (test.mjs runs it too, so the single file never goes stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const dir = dirname(fileURLToPath(import.meta.url));
const helper = readFileSync(join(dir, 'business-days.js'), 'utf8');
const worker = readFileSync(join(dir, 'worker.js'), 'utf8');

const importLine = /^import \{ dueDate \} from '\.\/business-days\.js';\r?\n/m;
if (!importLine.test(worker)) throw new Error('worker.js: the business-days import line was not found');

// In the helper only the names are exported; in one file they are plain functions and constants.
const helperBody = helper.replace(/^export (function|const) /gm, '$1 ');
if (/^export /m.test(helperBody)) throw new Error('business-days.js: an export form this script does not handle');

// Keep worker.js's header comment on top, then the helper, then the rest of the Worker.
const workerBody = worker.replace(importLine, '');
const marker = workerBody.indexOf('*/') + 2;
if (marker < 2) throw new Error('worker.js: header comment not found');

const out =
  '// GENERATED by build-single.mjs from worker.js and business-days.js. Do not edit; edit those and run the script again.\n' +
  workerBody.slice(0, marker) + '\n\n' +
  '// ---- business-days.js ----------------------------------------------------------------\n' +
  helperBody.replace(/^\/\*\*[\s\S]*?\*\/\n\n/, '').trimEnd() + '\n\n' +
  '// ---- worker.js -----------------------------------------------------------------------\n' +
  workerBody.slice(marker).replace(/^\s*\n/, '');

writeFileSync(join(dir, 'worker.single.js'), out);
console.log('wrote worker.single.js (' + out.split('\n').length + ' lines)');
