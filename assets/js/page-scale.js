/* Page scale for pages other than the homepage (desktop).
   The homepage zooms header, main and footer by one factor K (0.85 to 1.6): the largest K at which its header
   plus hero fill the window (assets/js/frame-fit.js). Any other page left at K = 1 therefore looks bigger or
   smaller than the homepage, depending on the window. This script gives such a page the SAME K.
   The homepage hero is not on this page, so K cannot be measured here. assets/js/page-scale-table.js holds the K
   the homepage picked for a grid of window sizes (generated by scripts/measure-home-scale.cjs); this script
   interpolates it for the current window and sets the zoom the same way frame-fit.js does.
   Window 901px wide and 560px tall or more only; below that, and with ?fit=off, the page stays at K = 1.
   Sets --kz (the scale) on <html>: viewport units inside the zoomed page are scaled too, so a rule that must
   span the window divides by it, e.g. calc(88vw / var(--kz, 1)). window.__pageScale.k is the scale.
   The page stays hidden until the first scale is set (html.ff-wait, set in <head>, page-scale.css). */
(function () {
  'use strict';
  var root = document.documentElement;
  var T = window.__pageScaleTable;
  var MIN_W = 901, MIN_H = 560;
  var header = document.getElementById('site-header'), main = document.querySelector('main'), footer = document.querySelector('.site-footer');
  var zoomed = [header, main, footer].filter(Boolean);

  function release() {
    if (!root.classList.contains('ff-wait')) return;
    requestAnimationFrame(function () {
      root.classList.remove('ff-wait');
      if (matchMedia('(prefers-reduced-motion: reduce)').matches) return;
      zoomed.forEach(function (el) {
        if (el.animate) el.animate([{ opacity: 0 }, { opacity: 1 }], { duration: 320, easing: 'cubic-bezier(0.16, 1, 0.3, 1)' });
      });
    });
  }

  // Bilinear lookup in the table; outside the measured grid the nearest edge is used.
  function lookup(w, h) {
    var gx = Math.min(Math.max((w - T.w0) / T.wStep, 0), T.k[0].length - 1);
    var gy = Math.min(Math.max((h - T.h0) / T.hStep, 0), T.k.length - 1);
    var x0 = Math.floor(gx), y0 = Math.floor(gy), x1 = Math.min(x0 + 1, T.k[0].length - 1), y1 = Math.min(y0 + 1, T.k.length - 1);
    var fx = gx - x0, fy = gy - y0;
    var a = T.k[y0][x0] * (1 - fx) + T.k[y0][x1] * fx, b = T.k[y1][x0] * (1 - fx) + T.k[y1][x1] * fx;
    return a * (1 - fy) + b * fy;
  }

  function setK(k) {
    zoomed.forEach(function (el) { el.style.zoom = k === 1 ? '' : String(k); });
    root.style.setProperty('--kz', String(k));
    window.__pageScale = { k: k, on: k !== 1 };
    dispatchEvent(new Event('pagescale'));
  }

  function apply() {
    var vw = root.clientWidth, vh = innerHeight;
    var on = T && !/[?&]fit=off/.test(location.search) && vw >= MIN_W && vh >= MIN_H;
    setK(on ? Math.floor(lookup(vw, vh) * 1000) / 1000 : 1);
    root.classList.toggle('ps-on', !!on);
    release();
  }

  if (!main || !header) { release(); return; }
  apply();
  var rz = 0;
  addEventListener('resize', function () { cancelAnimationFrame(rz); rz = requestAnimationFrame(apply); });
})();
