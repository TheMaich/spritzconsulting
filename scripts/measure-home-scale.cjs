/* Measures the page scale the homepage picks (assets/js/frame-fit.js) over a grid of window sizes and writes
   assets/js/page-scale-table.js, which assets/js/page-scale.js uses to give other pages the SAME scale.
   Run it again whenever the homepage hero (text, sizes, layout) changes:
     node scripts/measure-home-scale.cjs            (about 10 minutes)
   Needs playwright. Prints progress to stderr. */
const { chromium } = require('playwright');
const http = require('node:http'), fs = require('node:fs'), path = require('node:path');
const ROOT = path.resolve(__dirname, '..');
const MIME = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.woff2': 'font/woff2', '.png': 'image/png', '.webp': 'image/webp', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml' };
const server = http.createServer((q, r) => {
  let p = decodeURIComponent(q.url.split('?')[0]); if (p.endsWith('/')) p += 'index.html';
  const f = path.join(ROOT, p);
  if (!fs.existsSync(f) || fs.statSync(f).isDirectory()) { r.writeHead(404); return r.end('nf'); }
  r.writeHead(200, { 'Content-Type': MIME[path.extname(f)] || 'application/octet-stream' }); fs.createReadStream(f).pipe(r);
}).listen(0);

const W0 = 896, WSTEP = 64, WN = 47;     // 896 .. 3840 (windows narrower than 901px are not scaled)
const H0 = 560, HSTEP = 80, HN = 21;     // 560 .. 2160
const WS = Array.from({ length: WN }, (_, i) => W0 + i * WSTEP), HS = Array.from({ length: HN }, (_, i) => H0 + i * HSTEP);

(async () => {
  const browser = await chromium.launch();
  const url = 'http://127.0.0.1:' + server.address().port + '/';
  const rows = {};
  async function worker(hs) {
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 720 } }), p = await ctx.newPage();
    await p.goto(url); await p.waitForTimeout(2500);
    for (const h of hs) {
      const row = [];
      for (const w of WS) {
        await p.setViewportSize({ width: w, height: h }); await p.waitForTimeout(650);
        const k = await p.evaluate(() => window.__frameFit && window.__frameFit.on ? window.__frameFit.k : 1);
        row.push(Math.round(k * 1000) / 1000);
      }
      rows[h] = row; console.error('height', h, 'done');
    }
    await ctx.close();
  }
  const half = Math.ceil(HS.length / 2);
  await Promise.all([worker(HS.slice(0, half)), worker(HS.slice(half))]);
  const out = '/* Generated by scripts/measure-home-scale.cjs: the page scale the homepage picks, per window size.\n   Do not edit by hand. Rows are window heights, columns are window widths. */\n' +
    'window.__pageScaleTable = ' + JSON.stringify({ w0: W0, wStep: WSTEP, h0: H0, hStep: HSTEP, k: HS.map((h) => rows[h]) }) + ';\n';
  fs.writeFileSync(path.join(ROOT, 'assets/js/page-scale-table.js'), out);
  console.error('written', out.length, 'bytes');
  await browser.close(); server.close();
})();
